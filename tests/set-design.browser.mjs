import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require = createRequire(process.env.PLAYWRIGHT_PACKAGE || import.meta.url);
const {chromium} = require('@playwright/test');
const base = process.env.LIGERO_PREVIEW || 'http://127.0.0.1:4325';
const browser = await chromium.launch({channel:'msedge', headless:true});
const errors = [];
try {
  const page = await browser.newPage({viewport:{width:1440, height:900}});
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/services/set-designing.html`);
  await page.waitForFunction(() => document.documentElement.dataset.phase === 'ready');
  assert.equal(await page.locator('.film.is-active').getAttribute('data-id'), 'gift');
  const theme = await page.locator('.theme-switcher').boundingBox();
  const bts = await page.locator('.film.is-active .film-bts').boundingBox();
  assert.ok(theme.x >= bts.x + bts.width || bts.x >= theme.x + theme.width, 'theme setting cannot cover Behind the set');
  const button = page.locator('.film.is-active .film-bts');
  await button.click();
  await page.waitForSelector('#bts-drawer.is-open');
  assert.equal(await page.locator('.bts-frame').count(), 4);
  const before = await page.locator('.film.is-active').getAttribute('data-id');
  await page.keyboard.press('ArrowDown');
  await page.mouse.wheel(0, 400);
  await page.waitForTimeout(1500);
  assert.equal(await page.locator('.film.is-active').getAttribute('data-id'), before, 'film must not change under the drawer');
  const requests = [];
  page.on('request', r => requests.push(r.url()));
  await page.locator('.bts-open').nth(1).click();
  await page.waitForSelector('#still-dialog.is-open');
  await page.waitForFunction(() => !document.querySelector('#still-dialog').classList.contains('is-loading'));
  assert.ok(requests.some(u => /\/images\/gift-still-1\.webp$/.test(u)), 'original loads on click');
  assert.equal(await page.locator('.still-image').evaluate(i => i.naturalWidth), 3840);
  await page.keyboard.press('ArrowRight');
  assert.match(await page.locator('.still-count').textContent(), /03 \/ 04/);
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('#still-dialog').open);
  assert.equal(await page.locator('#bts-drawer').evaluate(d => d.open), true);
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('#bts-drawer').open);
  await page.keyboard.press('ArrowDown');
  await page.waitForFunction(() => document.documentElement.dataset.phase === 'transition');
  await page.waitForFunction(() => document.documentElement.dataset.phase === 'ready');
  assert.equal(await page.locator('.film.is-active').getAttribute('data-id'), 'fashion');
  await page.locator('.film.is-active .film-bts').click();
  await page.waitForSelector('#bts-drawer.is-open');
  const heavy = requests.filter(u => /\/images\/fashion-still-/.test(u));
  assert.equal(heavy.length, 0, 'heavy Fashion originals are not loaded before click');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('#bts-drawer').open);
  await page.keyboard.press('ArrowDown');
  await page.waitForFunction(() => document.documentElement.dataset.phase === 'ready' && document.querySelector('.film.is-active').dataset.id === 'brand');
  assert.equal(await page.locator('.film.is-active .film-bts').count(), 0);
  assert.deepEqual(errors, []);
} finally {
  await browser.close();
}
console.log('set-design browser checks passed');
